package com.starwake.fab;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.starwake.StarwakeMod;
import com.starwake.metal.Composition;
import com.starwake.metal.MaterialProperties;
import com.starwake.metal.MetalForm;
import com.starwake.metal.MetalItems;
import com.starwake.metal.Metallurgy;
import com.starwake.metal.Tempers;
import com.starwake.registry.ModComponents;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import net.minecraft.core.Registry;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.item.ItemStack;
import org.jspecify.annotations.Nullable;

/**
 * A Fabricator blueprint (M8e-1; synced dynamic registry {@code starwake:fabrication}, files in
 * {@code data/<ns>/starwake/fabrication/*.json}, generated by {@code tools/fabrication.py}): an output
 * item and count, energy, and inputs. Each input names what it takes (a metal {@code form}, a specific
 * {@code item}, or any item made of an {@code element}), how many, optional {@code base} element, and
 * property gates ({@code min}/{@code max}: yield, tensile, elongation, hardness, service, conductivity,
 * corrosion, density, purity, modulus). The {@code main} input's material (composition + temper) is
 * copied onto the product, so a nozzle remembers it is Inconel 718.
 *
 * <p>Quality: every gated input scores its weakest gate as actual / required (inverted for max gates),
 * capped at {@link #QUALITY_CAP}; the product's quality is the lowest score of its inputs, including the
 * qualities of component inputs. 1.0 = just meets the design; Mk parts turn the margin into a bonus (8e-2).
 */
public record Blueprint(Identifier output, int count, int order, double energy, List<Input> inputs) {
	public static final ResourceKey<Registry<Blueprint>> REGISTRY_KEY = ResourceKey.createRegistryKey(StarwakeMod.id("fabrication"));
	public static final double QUALITY_CAP = 1.5;

	public record Input(Optional<String> form, Optional<Identifier> item, Optional<String> element, int count, Optional<String> base,
			boolean main, Map<String, Double> min, Map<String, Double> max) {
		public static final Codec<Input> CODEC = RecordCodecBuilder.create(i -> i.group(
				Codec.STRING.optionalFieldOf("form").forGetter(Input::form),
				Identifier.CODEC.optionalFieldOf("item").forGetter(Input::item),
				Codec.STRING.optionalFieldOf("element").forGetter(Input::element),
				Codec.intRange(1, 64).optionalFieldOf("count", 1).forGetter(Input::count),
				Codec.STRING.optionalFieldOf("base").forGetter(Input::base),
				Codec.BOOL.optionalFieldOf("main", false).forGetter(Input::main),
				Codec.unboundedMap(Codec.STRING, Codec.DOUBLE).optionalFieldOf("min", Map.of()).forGetter(Input::min),
				Codec.unboundedMap(Codec.STRING, Codec.DOUBLE).optionalFieldOf("max", Map.of()).forGetter(Input::max)
		).apply(i, Input::new));

		/** Whether a stack is the right kind of thing (ignoring gates). */
		public boolean kind(ItemStack stack) {
			if (stack.isEmpty()) return false;
			if (item.isPresent()) {
				if (!BuiltInRegistries.ITEM.getKey(stack.getItem()).equals(item.get())) return false;
			} else if (form.isPresent()) {
				if (!MetalItems.formOf(stack).map(f -> f.id.equals(form.get())).orElse(false)) return false;
				if (MetalItems.compositionOf(stack).isEmpty()) return false;
			} else if (element.isPresent()) {
				if (!MetalItems.compositionOf(stack).map(c -> c.base().equals(element.get())).orElse(false)) return false;
			} else {
				return false;
			}
			if (base.isPresent()) return MetalItems.compositionOf(stack).map(c -> c.base().equals(base.get())).orElse(false);
			return true;
		}

		public List<String> gates() {
			List<String> out = new ArrayList<>();
			min.keySet().stream().sorted().forEach(k -> out.add("min:" + k));
			max.keySet().stream().sorted().forEach(k -> out.add("max:" + k));
			return out;
		}

		/** Index of the first gate the stack fails (in {@link #gates()} order), or -1. */
		public int failedGate(ItemStack stack) {
			List<String> gates = gates();
			for (int g = 0; g < gates.size(); g++) {
				String[] kv = gates.get(g).split(":");
				double actual = property(stack, kv[1]);
				double limit = kv[0].equals("min") ? min.get(kv[1]) : max.get(kv[1]);
				if (Double.isNaN(actual)) return g;
				if (kv[0].equals("min") ? actual < limit - 1e-9 : actual > limit + 1e-9) return g;
			}
			return -1;
		}

		/** Weakest-gate margin (1 = exactly meets), capped; NaN if there is nothing to judge (no gates, no quality). */
		public double quality(ItemStack stack) {
			double q = QUALITY_CAP;
			boolean any = false;
			for (var e : min.entrySet()) {
				double a = property(stack, e.getKey());
				if (e.getValue() > 0 && !Double.isNaN(a)) {
					q = Math.min(q, a / e.getValue());
					any = true;
				}
			}
			for (var e : max.entrySet()) {
				double a = property(stack, e.getKey());
				if (a > 0 && !Double.isNaN(a)) {
					q = Math.min(q, e.getValue() / a);
					any = true;
				}
			}
			Float own = stack.get(ModComponents.QUALITY);
			if (own != null) {
				q = Math.min(q, own);
				any = true;
			}
			return any ? Math.max(1, q) : Double.NaN;
		}
	}

	public static final Codec<Blueprint> CODEC = RecordCodecBuilder.create(i -> i.group(
			Identifier.CODEC.fieldOf("output").forGetter(Blueprint::output),
			Codec.intRange(1, 64).optionalFieldOf("count", 1).forGetter(Blueprint::count),
			Codec.INT.optionalFieldOf("order", 0).forGetter(Blueprint::order),
			Codec.DOUBLE.optionalFieldOf("energy", 100.0).forGetter(Blueprint::energy),
			Input.CODEC.listOf().fieldOf("inputs").forGetter(Blueprint::inputs)
	).apply(i, Blueprint::new));

	/** A material property of a stack (NaN when it has no material). Purity = wt% of the base element. */
	public static double property(ItemStack stack, String key) {
		Composition c = MetalItems.compositionOf(stack).orElse(null);
		if (c == null || c.isEmpty()) return Double.NaN;
		if (key.equals("purity")) return c.percent(c.base());
		MaterialProperties p = Tempers.properties(Metallurgy.analyze(c), Tempers.of(stack), MetalItems.formOf(stack).orElse(MetalForm.INGOT));
		return switch (key) {
			case "yield" -> p.yieldStrength();
			case "tensile" -> p.tensileStrength();
			case "elongation" -> p.elongation();
			case "hardness" -> p.hardness();
			case "service" -> p.serviceTemp();
			case "conductivity" -> p.conductivity();
			case "corrosion" -> p.corrosion();
			case "density" -> p.density();
			case "modulus" -> p.modulus();
			default -> Double.NaN;
		};
	}

	/** Per input: -2 missing, -1 satisfied, g >= 0 = the right items are there but fail gate g. */
	public record Match(int[] status, int[][] slots, double quality, int mainSlot) {
		public boolean complete() {
			for (int s : status) if (s != -1) return false;
			return true;
		}
	}

	/**
	 * Assigns slot items to inputs (each slot to at most one input, gates checked); quality is the lowest
	 * margin among inputs that have gates or carry a quality of their own.
	 */
	public Match match(List<ItemStack> slots) {
		int[] free = new int[slots.size()];
		for (int i = 0; i < slots.size(); i++) free[i] = slots.get(i).getCount();
		int[] status = new int[inputs.size()];
		int[][] used = new int[inputs.size()][slots.size()];
		double quality = QUALITY_CAP;
		boolean judged = false;
		int mainSlot = -1;
		for (int n = 0; n < inputs.size(); n++) {
			Input in = inputs.get(n);
			int need = in.count();
			int failed = -2;
			// Best margin first, so a strong alloy is used where it matters.
			List<Integer> order = new ArrayList<>();
			for (int i = 0; i < slots.size(); i++) if (free[i] > 0 && in.kind(slots.get(i))) order.add(i);
			order.sort((a, b) -> Double.compare(orOne(in.quality(slots.get(b))), orOne(in.quality(slots.get(a)))));
			double q = Double.NaN;
			for (int i : order) {
				ItemStack stack = slots.get(i);
				int g = in.failedGate(stack);
				if (g >= 0) {
					if (failed == -2) failed = g;
					continue;
				}
				int take = Math.min(need, free[i]);
				if (take <= 0) continue;
				used[n][i] = take;
				free[i] -= take;
				need -= take;
				double sq = in.quality(stack);
				if (!Double.isNaN(sq)) q = Double.isNaN(q) ? sq : Math.min(q, sq);
				if (in.main() && mainSlot < 0) mainSlot = i;
				if (need == 0) break;
			}
			if (need == 0) {
				status[n] = -1;
				if (!Double.isNaN(q)) {
					quality = Math.min(quality, q);
					judged = true;
				}
			} else {
				status[n] = failed;
				// Give back what this input took: it isn't satisfied.
				for (int i = 0; i < slots.size(); i++) {
					free[i] += used[n][i];
					used[n][i] = 0;
				}
			}
		}
		return new Match(status, used, judged ? Math.max(1, quality) : 1, mainSlot);
	}

	private static double orOne(double q) {
		return Double.isNaN(q) ? 1 : q;
	}

	/** The product for a complete match: output x count with the main input's material and the quality. */
	public ItemStack product(List<ItemStack> slots, Match match) {
		ItemStack out = new ItemStack(BuiltInRegistries.ITEM.getValue(output), count);
		if (match.mainSlot() >= 0) {
			ItemStack main = slots.get(match.mainSlot());
			MetalItems.compositionOf(main).ifPresent(c -> out.set(ModComponents.COMPOSITION, c));
			Tempers.Temper t = Tempers.of(main);
			if (!t.state().isEmpty()) out.set(ModComponents.TEMPER, t.withProgress(0));
		}
		out.set(ModComponents.QUALITY, (float) (Math.round(match.quality() * 100) / 100.0));
		return out;
	}

	/** Display order: by {@code order}, then id. */
	public static List<Map.Entry<Identifier, Blueprint>> sorted(Registry<Blueprint> registry) {
		List<Map.Entry<Identifier, Blueprint>> list = new ArrayList<>();
		registry.listElements().forEach(h -> list.add(Map.entry(h.key().identifier(), h.value())));
		list.sort((a, b) -> a.getValue().order() != b.getValue().order() ? Integer.compare(a.getValue().order(), b.getValue().order())
				: a.getKey().toString().compareTo(b.getKey().toString()));
		return list;
	}

	public static @Nullable String unit(String key) {
		return switch (key) {
			case "yield", "tensile" -> "MPa";
			case "elongation", "purity" -> "%";
			case "hardness" -> "HV";
			case "service" -> "C";
			case "conductivity" -> "% IACS";
			case "corrosion" -> "/10";
			case "density" -> "g/cm3";
			case "modulus" -> "GPa";
			default -> null;
		};
	}
}
