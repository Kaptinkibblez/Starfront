package com.starwake.ship.weapon;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.starwake.StarwakeMod;
import java.util.HashMap;
import java.util.Map;
import java.util.Optional;
import net.fabricmc.fabric.api.resource.v1.ResourceLoader;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.FileToIdConverter;
import net.minecraft.resources.Identifier;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.resources.ResourceManager;
import net.minecraft.server.packs.resources.SimpleJsonResourceReloadListener;
import net.minecraft.util.profiling.ProfilerFiller;
import net.minecraft.world.level.block.Block;
import org.jspecify.annotations.Nullable;

/**
 * What a ship weapon does (M11), from {@code data/<ns>/starwake/ship_weapon/<block path>.json} (generated by
 * {@code tools/ship_weapons.py} for every Mk). Server data.
 *
 * @param kind         "ballistic" (ammo, partly ignores shields) or "energy" (capacitor, strong against shields)
 * @param damage       damage per hit (hull points; a tenth of it in hearts against living things)
 * @param speed        projectile speed, m/s
 * @param rate         shots per second
 * @param range        metres before the shot fades
 * @param spread       random cone, degrees
 * @param gimbalCone   how far a gimballed mount can turn from its facing, degrees
 * @param gimbalFactor damage multiplier on a gimballed mount (fixed mounts hit harder)
 * @param energy       kJ drawn from the weapon capacitor per shot (energy weapons)
 * @param heat         kJ of heat added to the ship per shot
 * @param capacitor    kJ of weapon capacitor this weapon brings
 * @param ammo         ammo item (ballistic weapons), rounds per item in {@code roundsPerItem}
 * @param shieldFactor share of the damage shields take (1 = all; ballistic below 1 so some passes straight through)
 * @param breakDamage  a hit at least this strong breaks blocks around the impact even with hull points left
 */
public record WeaponSpec(String kind, double damage, double speed, double rate, double range, double spread, double gimbalCone,
		double gimbalFactor, double energy, double heat, double capacitor, Optional<Identifier> ammo, int roundsPerItem,
		double shieldFactor, double breakDamage) {
	public static final Codec<WeaponSpec> CODEC = RecordCodecBuilder.create(i -> i.group(
			Codec.STRING.fieldOf("kind").forGetter(WeaponSpec::kind),
			Codec.DOUBLE.fieldOf("damage").forGetter(WeaponSpec::damage),
			Codec.DOUBLE.fieldOf("speed").forGetter(WeaponSpec::speed),
			Codec.DOUBLE.fieldOf("rate").forGetter(WeaponSpec::rate),
			Codec.DOUBLE.fieldOf("range").forGetter(WeaponSpec::range),
			Codec.DOUBLE.optionalFieldOf("spread", 0.3).forGetter(WeaponSpec::spread),
			Codec.DOUBLE.optionalFieldOf("gimbal_cone", 20.0).forGetter(WeaponSpec::gimbalCone),
			Codec.DOUBLE.optionalFieldOf("gimbal_factor", 0.8).forGetter(WeaponSpec::gimbalFactor),
			Codec.DOUBLE.optionalFieldOf("energy", 0.0).forGetter(WeaponSpec::energy),
			Codec.DOUBLE.optionalFieldOf("heat", 0.0).forGetter(WeaponSpec::heat),
			Codec.DOUBLE.optionalFieldOf("capacitor", 0.0).forGetter(WeaponSpec::capacitor),
			Identifier.CODEC.optionalFieldOf("ammo").forGetter(WeaponSpec::ammo),
			Codec.INT.optionalFieldOf("rounds_per_item", 1).forGetter(WeaponSpec::roundsPerItem),
			Codec.DOUBLE.optionalFieldOf("shield_factor", 1.0).forGetter(WeaponSpec::shieldFactor),
			Codec.DOUBLE.optionalFieldOf("break_damage", 1.0e9).forGetter(WeaponSpec::breakDamage)
	).apply(i, WeaponSpec::new));

	private static Map<Identifier, WeaponSpec> specs = Map.of();

	public boolean energyWeapon() {
		return kind.equals("energy");
	}

	/** The spec for a weapon block, or null if it isn't one. */
	public static @Nullable WeaponSpec of(Block block) {
		return specs.get(BuiltInRegistries.BLOCK.getKey(block));
	}

	public static void init() {
		ResourceLoader.get(PackType.SERVER_DATA).registerReloadListener(StarwakeMod.id("ship_weapon"),
				new SimpleJsonResourceReloadListener<>(CODEC, FileToIdConverter.json("starwake/ship_weapon")) {
					@Override
					protected void apply(Map<Identifier, WeaponSpec> loaded, ResourceManager manager, ProfilerFiller profiler) {
						specs = new HashMap<>(loaded);
					}
				});
	}
}
