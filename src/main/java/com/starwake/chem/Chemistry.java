package com.starwake.chem;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.starwake.StarwakeMod;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import net.minecraft.resources.Identifier;

/**
 * The periodic table and the minerals that carry it (M5; user: "the entire periodic table").
 *
 * <p>Loaded once at startup from bundled data ({@code /starwake/chemistry/elements.json} and
 * {@code minerals.json}, generated by {@code tools/periodic_table.py}) because elements and ore
 * minerals become items and blocks, which must be registered before datapacks load. Both sides
 * read the same files, so tooltips and the Wristcom need no syncing.
 *
 * <p>Every element (all 118) has an item in its refined form. Every naturally occurring element
 * (Z 1-94) has a real source: an ore mineral (as a major or trace constituent), the atmosphere,
 * or water/brine. Synthetic elements come from reactors later (Milestone 8). The future
 * metallurgy system refines minerals into elements and alloys using these compositions.
 */
public final class Chemistry {
	/** One element. */
	public record Element(int z, String symbol, String name, String category, String phase, double mass, double density,
			double meltingPoint, int color, String form, Identifier item, String occurrence, boolean radioactive, List<String> sources) {}

	/** One ore mineral: mass fractions of its major elements, plus trace by-products. */
	public record Mineral(String id, String formula, String tool, Map<String, Double> composition, List<String> trace,
			Identifier block, Optional<Identifier> raw, boolean registered, Optional<Worldgen> worldgen) {}

	public record Worldgen(int size, int count, int minY, int maxY) {}

	private static List<Element> elements = List.of();
	private static List<Mineral> minerals = List.of();
	private static Map<String, Element> bySymbol = Map.of();
	private static Map<Identifier, Element> byItem = Map.of();
	private static Map<Identifier, Mineral> byMineralItem = Map.of();

	private Chemistry() {}

	public static synchronized void load() {
		if (!elements.isEmpty()) return;
		List<Element> e = new ArrayList<>();
		for (JsonElement json : read("elements.json")) {
			JsonObject o = json.getAsJsonObject();
			List<String> sources = new ArrayList<>();
			o.getAsJsonArray("sources").forEach(s -> sources.add(s.getAsString()));
			e.add(new Element(o.get("z").getAsInt(), o.get("symbol").getAsString(), o.get("name").getAsString(),
					o.get("category").getAsString(), o.get("phase").getAsString(), o.get("mass").getAsDouble(),
					o.get("density").getAsDouble(), o.get("melting_point").getAsDouble(),
					Integer.parseInt(o.get("color").getAsString().substring(1), 16) | 0xFF000000, o.get("form").getAsString(),
					Identifier.parse(o.get("item").getAsString()), o.get("occurrence").getAsString(), o.get("radioactive").getAsBoolean(),
					List.copyOf(sources)));
		}
		List<Mineral> m = new ArrayList<>();
		for (JsonElement json : read("minerals.json")) {
			JsonObject o = json.getAsJsonObject();
			Map<String, Double> composition = new LinkedHashMap<>();
			o.getAsJsonObject("composition").entrySet().forEach(en -> composition.put(en.getKey(), en.getValue().getAsDouble()));
			List<String> trace = new ArrayList<>();
			o.getAsJsonArray("trace").forEach(t -> trace.add(t.getAsString()));
			Optional<Worldgen> gen = Optional.empty();
			if (o.has("worldgen") && o.get("worldgen").isJsonObject()) {
				JsonObject g = o.getAsJsonObject("worldgen");
				gen = Optional.of(new Worldgen(g.get("size").getAsInt(), g.get("count").getAsInt(), g.get("min_y").getAsInt(),
						g.get("max_y").getAsInt()));
			}
			m.add(new Mineral(o.get("id").getAsString(), o.get("formula").getAsString(), o.get("tool").getAsString(),
					Collections.unmodifiableMap(composition), List.copyOf(trace), Identifier.parse(o.get("block").getAsString()),
					o.get("raw").isJsonNull() ? Optional.empty() : Optional.of(Identifier.parse(o.get("raw").getAsString())),
					o.get("registered").getAsBoolean(), gen));
		}
		elements = List.copyOf(e);
		minerals = List.copyOf(m);
		Map<String, Element> symbols = new HashMap<>();
		Map<Identifier, Element> items = new HashMap<>();
		for (Element el : elements) {
			symbols.put(el.symbol(), el);
			items.put(el.item(), el);
		}
		Map<Identifier, Mineral> mineralItems = new HashMap<>();
		for (Mineral mi : minerals) {
			mineralItems.put(mi.block(), mi);
			mi.raw().ifPresent(raw -> mineralItems.put(raw, mi));
		}
		bySymbol = Map.copyOf(symbols);
		byItem = Map.copyOf(items);
		byMineralItem = Map.copyOf(mineralItems);
		StarwakeMod.LOGGER.info("Chemistry: {} elements, {} minerals", elements.size(), minerals.size());
	}

	private static JsonArray read(String file) {
		String path = "/starwake/chemistry/" + file;
		try (InputStream in = Chemistry.class.getResourceAsStream(path)) {
			if (in == null) throw new IllegalStateException("missing " + path);
			return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8)).getAsJsonArray();
		} catch (java.io.IOException ex) {
			throw new IllegalStateException("can't read " + path, ex);
		}
	}

	public static List<Element> elements() {
		load();
		return elements;
	}

	public static List<Mineral> minerals() {
		load();
		return minerals;
	}

	public static Optional<Element> element(String symbol) {
		load();
		return Optional.ofNullable(bySymbol.get(symbol));
	}

	/** The element an item is (its refined form, or the vanilla ingot for Fe/Cu/Au). */
	public static Optional<Element> elementOf(Identifier item) {
		load();
		return Optional.ofNullable(byItem.get(item));
	}

	/** The mineral an ore block or raw mineral item is made of. */
	public static Optional<Mineral> mineralOf(Identifier item) {
		load();
		return Optional.ofNullable(byMineralItem.get(item));
	}
}
