package com.starwake.process;

import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.starwake.chem.Chemistry;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.HashSet;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.Identifier;

/**
 * Chemical species for process chemistry (M8c): minerals, oxides, sulfides, slags, gases, organics
 * and every element, from bundled {@code /starwake/chemistry/species.json} (generated by
 * {@code tools/chemistry_process.py}). Read on both sides because species become chemical fluids
 * and tooltips. Each species knows its formula, so molar mass and element mass fractions are
 * computed, and every reaction can be checked for balance.
 *
 * <p>Also loads {@code ores.json}: what raw ore chunks, fuels and fluxes are made of (assay + kg).
 */
public final class Species {
	public enum Kind { METAL, ELEMENT, SULFIDE, OXIDE, SILICATE, CARBONATE, SULFATE, PHOSPHATE, HALIDE, GAS, ORGANIC, CARBON, WATER }

	public record Info(String id, String name, String formula, Kind kind, double density, double melting, double boiling, Set<String> flags,
			double toxicity, int color, Map<String, Double> elements, double molarMass, int index, double potential, double solubility,
			double activity, double gamma) {
		/** kg that dissolve per kg of water (infinite when unlimited). */
		public double solubilityLimit() {
			return Double.isNaN(solubility) ? Double.POSITIVE_INFINITY : solubility;
		}

		/** Dissolves into aqueous solutions. */
		public boolean soluble() {
			return flags.contains("soluble") || kind == Kind.WATER;
		}

		public Component displayName() {
			return Component.translatableWithFallback("species.starwake." + id.toLowerCase().replaceAll("[^a-z0-9]", "_"), name);
		}

		public boolean has(String flag) {
			return flags.contains(flag);
		}

		public boolean gasAtRoom() {
			return boiling < 25;
		}

		public boolean liquidAtRoom() {
			return melting < 25 && boiling >= 25;
		}

		/** A metal or semimetal element. */
		public boolean metallic() {
			return kind == Kind.METAL;
		}
	}

	/** A raw item's make-up: kg per item and its assay. */
	public record Feed(double mass, Assay assay) {}

	/**
	 * Lithophile oxide-formers: in a smelter these stay in the slag even when a metal bath exists
	 * (Goldschmidt; plus the refractory oxide formers Nb and Ta).
	 */
	public static final Set<String> SLAG_FORMERS = Set.of("Li", "Be", "B", "Na", "Mg", "Al", "Si", "K", "Ca", "Sc", "Ti", "Rb", "Sr", "Y", "Zr",
			"Nb", "Cs", "Ba", "La", "Ce", "Pr", "Nd", "Pm", "Sm", "Eu", "Gd", "Tb", "Dy", "Ho", "Er", "Tm", "Yb", "Lu", "Hf", "Ta", "Fr",
			"Ra", "Ac", "Th", "Pa", "U", "Np", "Pu", "F", "Cl", "Br", "I");
	/** Chalcophile elements: they follow sulfur into the matte when there is one. */
	public static final Set<String> CHALCOPHILE = Set.of("Cu", "Ag", "Zn", "Cd", "Hg", "Ga", "In", "Tl", "Pb", "As", "Sb", "Bi", "S", "Se", "Te",
			"Ge", "Po");

	private static final Pattern TOKEN = Pattern.compile("([A-Z][a-z]?|\\(|\\)|\\d+(?:\\.\\d+)?)");
	private static Map<String, Info> byId = Map.of();
	private static List<Info> list = List.of();
	private static Map<Identifier, Feed> feeds = Map.of();

	private Species() {}

	private static synchronized void load() {
		if (!list.isEmpty()) return;
		List<Info> out = new ArrayList<>();
		Map<String, Info> map = new HashMap<>();
		for (JsonElement json : read("species.json").getAsJsonArray()) {
			JsonObject o = json.getAsJsonObject();
			String formula = o.get("formula").getAsString();
			Map<String, Double> atoms = parse(formula);
			double molar = 0;
			for (var e : atoms.entrySet()) molar += Chemistry.element(e.getKey()).map(Chemistry.Element::mass).orElse(0.0) * e.getValue();
			// Isotopes (M8f: D2O, D2, He3) are written as their element but weighed as the isotope.
			if (o.has("molar")) molar = o.get("molar").getAsDouble();
			Map<String, Double> fractions = new LinkedHashMap<>();
			for (var e : atoms.entrySet()) {
				double m = Chemistry.element(e.getKey()).map(Chemistry.Element::mass).orElse(0.0) * e.getValue();
				fractions.put(e.getKey(), molar <= 0 ? 0 : m / molar);
			}
			Set<String> flags = new HashSet<>();
			o.getAsJsonArray("flags").forEach(f -> flags.add(f.getAsString()));
			Info info = new Info(o.get("id").getAsString(), o.get("name").getAsString(), formula, Kind.valueOf(o.get("kind").getAsString().toUpperCase()),
					o.get("density").getAsDouble(), o.get("melting").getAsDouble(), o.get("boiling").getAsDouble(), Set.copyOf(flags),
					o.get("toxicity").getAsDouble(), Integer.parseInt(o.get("color").getAsString().substring(1), 16), Map.copyOf(fractions), molar,
					out.size(), o.has("potential") ? o.get("potential").getAsDouble() : Double.NaN,
					o.has("solubility") ? o.get("solubility").getAsDouble() : Double.NaN,
					o.has("activity") ? o.get("activity").getAsDouble() : 0, o.has("gamma") ? o.get("gamma").getAsDouble() : 0);
			out.add(info);
			map.put(info.id(), info);
		}
		byId = Map.copyOf(map);
		list = List.copyOf(out);
		Map<Identifier, Feed> f = new HashMap<>();
		for (var e : read("ores.json").getAsJsonObject().entrySet()) {
			JsonObject o = e.getValue().getAsJsonObject();
			Map<String, Double> assay = new HashMap<>();
			o.getAsJsonObject("assay").entrySet().forEach(a -> assay.put(a.getKey(), a.getValue().getAsDouble()));
			f.put(Identifier.parse(e.getKey()), new Feed(o.get("mass").getAsDouble(), Assay.of(assay)));
		}
		feeds = Map.copyOf(f);
	}

	private static JsonElement read(String file) {
		try (var in = Species.class.getResourceAsStream("/starwake/chemistry/" + file)) {
			if (in == null) throw new IllegalStateException("Missing bundled " + file);
			return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8));
		} catch (java.io.IOException e) {
			throw new IllegalStateException(e);
		}
	}

	/** Atoms per formula unit: "Ca5(PO4)3F" -> Ca 5, P 3, O 12, F 1. */
	public static Map<String, Double> parse(String formula) {
		List<Map<String, Double>> stack = new ArrayList<>();
		stack.add(new LinkedHashMap<>());
		List<String> tokens = new ArrayList<>();
		Matcher m = TOKEN.matcher(formula);
		while (m.find()) tokens.add(m.group());
		for (int i = 0; i < tokens.size(); i++) {
			String t = tokens.get(i);
			boolean numberNext = i + 1 < tokens.size() && Character.isDigit(tokens.get(i + 1).charAt(0));
			if (t.equals("(")) {
				stack.add(new LinkedHashMap<>());
			} else if (t.equals(")")) {
				Map<String, Double> group = stack.removeLast();
				double n = numberNext ? Double.parseDouble(tokens.get(++i)) : 1;
				group.forEach((k, v) -> stack.getLast().merge(k, v * n, Double::sum));
			} else if (!Character.isDigit(t.charAt(0))) {
				double n = numberNext ? Double.parseDouble(tokens.get(++i)) : 1;
				stack.getLast().merge(t, n, Double::sum);
			}
		}
		return stack.getFirst();
	}

	public static Optional<Info> get(String id) {
		load();
		return Optional.ofNullable(byId.get(id));
	}

	public static Info require(String id) {
		load();
		Info info = byId.get(id);
		if (info == null) throw new IllegalArgumentException("Unknown species " + id);
		return info;
	}

	public static List<Info> all() {
		load();
		return list;
	}

	public static Info byIndex(int index) {
		load();
		return index >= 0 && index < list.size() ? list.get(index) : list.getFirst();
	}

	/** What an item is made of, if it is an ore chunk, fuel, flux or feedstock. */
	public static Optional<Feed> feed(Identifier item) {
		load();
		return Optional.ofNullable(feeds.get(item));
	}

	public static Map<Identifier, Feed> feeds() {
		load();
		return feeds;
	}
}
