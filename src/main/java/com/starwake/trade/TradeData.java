package com.starwake.trade;

import com.mojang.serialization.Codec;
import com.mojang.serialization.codecs.RecordCodecBuilder;
import com.starwake.StarwakeMod;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import net.fabricmc.fabric.api.resource.v1.ResourceLoader;
import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.ComponentSerialization;
import net.minecraft.resources.FileToIdConverter;
import net.minecraft.resources.Identifier;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.resources.ResourceManager;
import net.minecraft.server.packs.resources.SimpleJsonResourceReloadListener;
import net.minecraft.util.profiling.ProfilerFiller;

/**
 * Trade data (M7), server side, all reloadable datapack JSON under {@code data/<ns>/starwake/}:
 * <ul>
 *   <li>{@code hub_template/}: hub layouts (blueprint format plus pressurized boxes, NPC spawns,
 *       beacon and ground layer; generated by {@code tools/hub_templates.py});</li>
 *   <li>{@code hub_economy/}: what a kind of hub buys and sells (commodity groups with price
 *       multipliers) and which outfitter shop it runs;</li>
 *   <li>{@code commodity/}: commodity groups, item -> base price in credits (generated by
 *       {@code tools/trade_data.py} from real elemental abundances);</li>
 *   <li>{@code shop/}: outfitter stock, item -> price (+ minimum reputation).</li>
 * </ul>
 */
public final class TradeData {
	/** A hub layout. Layers bottom first; ' ' leaves the world, '.' forces air. */
	public record Template(Optional<Component> name, Map<String, String> palette, List<List<String>> layers, List<List<Integer>> pressurized,
			List<NpcSpawn> npcs, List<Integer> beacon, int ground) {
		public static final Codec<Template> CODEC = RecordCodecBuilder.create(i -> i.group(
				ComponentSerialization.CODEC.optionalFieldOf("name").forGetter(Template::name),
				Codec.unboundedMap(Codec.STRING, Codec.STRING).fieldOf("palette").forGetter(Template::palette),
				Codec.STRING.listOf().listOf().fieldOf("layers").forGetter(Template::layers),
				Codec.INT.listOf().listOf().optionalFieldOf("pressurized", List.of()).forGetter(Template::pressurized),
				NpcSpawn.CODEC.listOf().optionalFieldOf("npcs", List.of()).forGetter(Template::npcs),
				Codec.INT.listOf().optionalFieldOf("beacon", List.of(0, 0, 0)).forGetter(Template::beacon),
				Codec.INT.optionalFieldOf("ground", 0).forGetter(Template::ground)
		).apply(i, Template::new));

		public int sizeX() {
			return layers.isEmpty() || layers.getFirst().isEmpty() ? 0 : layers.getFirst().getFirst().length();
		}

		public int sizeY() {
			return layers.size();
		}

		public int sizeZ() {
			return layers.isEmpty() ? 0 : layers.getFirst().size();
		}
	}

	public record NpcSpawn(List<Integer> pos, String role) {
		public static final Codec<NpcSpawn> CODEC = RecordCodecBuilder.create(i -> i.group(
				Codec.INT.listOf().fieldOf("pos").forGetter(NpcSpawn::pos),
				Codec.STRING.fieldOf("role").forGetter(NpcSpawn::role)
		).apply(i, NpcSpawn::new));
	}

	/** One commodity group a hub trades, with its price multiplier and stock size. */
	public record Trade(String group, double price, int stock, boolean local) {
		public static final Codec<Trade> CODEC = RecordCodecBuilder.create(i -> i.group(
				Codec.STRING.fieldOf("group").forGetter(Trade::group),
				Codec.doubleRange(0.05, 20).optionalFieldOf("price", 1.0).forGetter(Trade::price),
				Codec.intRange(1, 100000).optionalFieldOf("stock", 256).forGetter(Trade::stock),
				Codec.BOOL.optionalFieldOf("local", false).forGetter(Trade::local)
		).apply(i, Trade::new));
	}

	/**
	 * A kind of hub's economy.
	 *
	 * @param name      suffix for hub names ("Mining Camp")
	 * @param sells     groups it produces (well stocked, cheap)
	 * @param buys      groups it consumes (scarce, pays well)
	 * @param outfitter its outfitter shop id
	 */
	public record Economy(Component name, List<Trade> sells, List<Trade> buys, Optional<Identifier> outfitter) {
		public static final Codec<Economy> CODEC = RecordCodecBuilder.create(i -> i.group(
				ComponentSerialization.CODEC.fieldOf("name").forGetter(Economy::name),
				Trade.CODEC.listOf().optionalFieldOf("sells", List.of()).forGetter(Economy::sells),
				Trade.CODEC.listOf().optionalFieldOf("buys", List.of()).forGetter(Economy::buys),
				Identifier.CODEC.optionalFieldOf("outfitter").forGetter(Economy::outfitter)
		).apply(i, Economy::new));
	}

	/** A commodity group: item -> base price. */
	public record Commodities(Map<Identifier, Double> items) {
		public static final Codec<Commodities> CODEC = RecordCodecBuilder.create(i -> i.group(
				Codec.unboundedMap(Identifier.CODEC, Codec.DOUBLE).fieldOf("items").forGetter(Commodities::items)
		).apply(i, Commodities::new));
	}

	/** An outfitter's stock line. */
	public record ShopItem(Identifier item, long price, int count, int rep) {
		public static final Codec<ShopItem> CODEC = RecordCodecBuilder.create(i -> i.group(
				Identifier.CODEC.fieldOf("item").forGetter(ShopItem::item),
				Codec.LONG.fieldOf("price").forGetter(ShopItem::price),
				Codec.intRange(1, 64).optionalFieldOf("count", 1).forGetter(ShopItem::count),
				Codec.INT.optionalFieldOf("rep", -100).forGetter(ShopItem::rep)
		).apply(i, ShopItem::new));
	}

	public record Shop(List<ShopItem> items) {
		public static final Codec<Shop> CODEC = RecordCodecBuilder.create(i -> i.group(
				ShopItem.CODEC.listOf().fieldOf("items").forGetter(Shop::items)
		).apply(i, Shop::new));
	}

	private static Map<Identifier, Template> templates = Map.of();
	private static Map<Identifier, Economy> economies = Map.of();
	private static Map<Identifier, Commodities> commodities = Map.of();
	private static Map<Identifier, Shop> shops = Map.of();
	private static int generation;

	private TradeData() {}

	public static void init() {
		listen("hub_template", Template.CODEC, m -> templates = m);
		listen("hub_economy", Economy.CODEC, m -> economies = m);
		listen("commodity", Commodities.CODEC, m -> commodities = m);
		listen("shop", Shop.CODEC, m -> shops = m);
	}

	private static <T> void listen(String folder, Codec<T> codec, java.util.function.Consumer<Map<Identifier, T>> sink) {
		ResourceLoader.get(PackType.SERVER_DATA).registerReloadListener(StarwakeMod.id(folder),
				new SimpleJsonResourceReloadListener<>(codec, FileToIdConverter.json("starwake/" + folder)) {
					@Override
					protected void apply(Map<Identifier, T> loaded, ResourceManager manager, ProfilerFiller profiler) {
						sink.accept(Map.copyOf(loaded));
						generation++;
						StarwakeMod.LOGGER.info("Loaded {} {} entries", loaded.size(), folder);
					}
				});
	}

	/** Bumps on every reload (caches keyed on data can check it). */
	public static int generation() {
		return generation;
	}

	public static Optional<Template> template(String id) {
		return Optional.ofNullable(templates.get(id(id)));
	}

	public static Optional<Economy> economy(String id) {
		return Optional.ofNullable(economies.get(id(id)));
	}

	public static Optional<Commodities> group(String id) {
		return Optional.ofNullable(commodities.get(id(id)));
	}

	public static Map<Identifier, Commodities> groups() {
		return commodities;
	}

	public static Optional<Shop> shop(Identifier id) {
		return Optional.ofNullable(shops.get(id));
	}

	/** Base price of an item in any commodity group (0 if it isn't a commodity). */
	public static double basePrice(Identifier item) {
		for (Commodities c : commodities.values()) {
			Double p = c.items().get(item);
			if (p != null) return p;
		}
		return 0;
	}

	private static Identifier id(String id) {
		return id.contains(":") ? Identifier.parse(id) : StarwakeMod.id(id);
	}
}
